// The PostgreSQL adapter (db/postgres.ts) on a real server: the same interface and behavior as the SQLite one
// (test/database.test.ts), plus what only a server has (parallel connections). Made-up rows only. Skipped without
// DATABASE_URL (see test/pg.js).
import { test } from 'node:test';
import assert from 'node:assert/strict';
import { createPostgresDatabase } from '../db/postgres.ts';
import { scopeDatabase } from '../db/scope.js';
import { freshPgDatabase, pgSkip } from './pg.js';

const deferred = () => {
  let resolve!: (v?: unknown) => void;
  const promise = new Promise((r) => { resolve = r; });
  return { promise, resolve };
};

async function scratch() {
  const fresh = await freshPgDatabase();
  const db = createPostgresDatabase(fresh.pool);
  await db.exec('CREATE TABLE t (id INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY, user_id TEXT, name TEXT, n INTEGER, x DOUBLE PRECISION)');
  return { db, fresh };
}

test('statements: get, all, run and pluck give what the SQLite interface gives', { skip: pgSkip }, async () => {
  const { db, fresh } = await scratch();
  try {
    assert.equal(db.engine, 'postgres');
    assert.equal(db.raw, null);
    assert.deepEqual(await db.prepare('INSERT INTO t (name, n) VALUES (?, ?) RETURNING id').get('a', 1), { id: 1 });
    await db.prepare('INSERT INTO t (name, n, x) VALUES (@name, @n, @x)').run({ name: 'b', n: 2, x: 1.5 });
    assert.deepEqual(await db.prepare('SELECT name, n FROM t ORDER BY id').all(), [{ name: 'a', n: 1 }, { name: 'b', n: 2 }]);
    assert.deepEqual(await db.prepare('SELECT id, name, x FROM t WHERE id = ?').get(2), { id: 2, name: 'b', x: 1.5 });
    assert.equal(await db.prepare('SELECT * FROM t WHERE id = 99').get(), undefined);
    assert.deepEqual(await db.prepare('SELECT name FROM t ORDER BY id').pluck().all(), ['a', 'b']);
    assert.deepEqual(await db.prepare('UPDATE t SET n = n + 1').run(), { changes: 2 });
    await assert.rejects(db.prepare('SELECT * FROM t WHERE id = ?').get(), /Too few parameter/);
    await db.exec('DELETE FROM t WHERE id = 1; DELETE FROM t WHERE id = 2');
    assert.equal(await db.prepare('SELECT COUNT(*) FROM t').pluck().get(), 0);
  } finally {
    await fresh.drop();
  }
});

test('numbers: count, sum and avg come back as numbers; a bigint past 2^53 throws', { skip: pgSkip }, async () => {
  const { db, fresh } = await scratch();
  try {
    for (const n of [1, 2, 4]) await db.prepare('INSERT INTO t (n) VALUES (?)').run(n);
    assert.deepEqual(await db.prepare('SELECT COUNT(*) AS c, SUM(n) AS s, AVG(n) AS a, MAX(n) AS m FROM t').get(),
      { c: 3, s: 7, a: 7 / 3, m: 4 });
    assert.equal(await db.prepare('SELECT SUM(n) FROM t WHERE n > 9').pluck().get(), null);
    await assert.rejects(db.prepare('SELECT 9007199254740993::bigint').pluck().get(), /too large/);
  } finally {
    await fresh.drop();
  }
});

test('sessions run in UTC', { skip: pgSkip }, async () => {
  const { db, fresh } = await scratch();
  try {
    assert.equal(await db.prepare('SHOW TIME ZONE').pluck().get(), 'UTC');
  } finally {
    await fresh.drop();
  }
});

test('tx: commits on resolve, rolls back on throw, and a nested tx is a savepoint that rolls back alone', { skip: pgSkip }, async () => {
  const { db, fresh } = await scratch();
  try {
    const insert = (name: string) => db.prepare('INSERT INTO t (name) VALUES (?)').run(name);
    const names = () => db.prepare('SELECT name FROM t ORDER BY id').pluck().all();
    assert.equal(await db.tx(async () => { await insert('kept'); return 'done'; }), 'done');
    await assert.rejects(db.tx(async () => { await insert('dropped'); throw new Error('stop'); }), /stop/);
    assert.deepEqual(await names(), ['kept']);
    await db.tx(async () => {
      await insert('outer');
      await assert.rejects(db.tx(async () => { await insert('inner'); throw new Error('inner fails'); }));
      await db.tx(async () => { await insert('inner kept'); });
    });
    assert.deepEqual(await names(), ['kept', 'outer', 'inner kept']);
  } finally {
    await fresh.drop();
  }
});

test('a failed statement aborts its transaction (unlike SQLite): the tx rejects and nothing in it is kept', { skip: pgSkip }, async () => {
  const { db, fresh } = await scratch();
  try {
    await assert.rejects(db.tx(async () => {
      await db.prepare('INSERT INTO t (name) VALUES (?)').run('first');
      await db.prepare('SELECT nope FROM t').all().catch(() => null);
      await db.prepare('INSERT INTO t (name) VALUES (?)').run('second');
    }), /current transaction is aborted/);
    assert.equal(await db.prepare('SELECT COUNT(*) FROM t').pluck().get(), 0);
  } finally {
    await fresh.drop();
  }
});

test('a transaction\'s statements see its own writes; other contexts see only committed rows and do not wait', { skip: pgSkip }, async () => {
  const { db, fresh } = await scratch();
  try {
    const inside = deferred();
    const release = deferred();
    const running = db.tx(async () => {
      await db.prepare('INSERT INTO t (name) VALUES (?)').run('pending');
      assert.equal(await db.prepare('SELECT COUNT(*) FROM t').pluck().get(), 1);
      inside.resolve();
      await release.promise;
    });
    await inside.promise;
    assert.equal(await db.prepare('SELECT COUNT(*) FROM t').pluck().get(), 0, 'outside, not yet committed');
    release.resolve();
    await running;
    assert.equal(await db.prepare('SELECT COUNT(*) FROM t').pluck().get(), 1);
  } finally {
    await fresh.drop();
  }
});

test('transactions run one at a time, as on SQLite: a read then write in each never interleaves', { skip: pgSkip }, async () => {
  const { db, fresh } = await scratch();
  try {
    await db.prepare('INSERT INTO t (name, n) VALUES (?, 0)').run('counter');
    const bump = () => db.tx(async () => {
      const n = await db.prepare("SELECT n FROM t WHERE name = 'counter'").pluck().get();
      await new Promise((r) => setTimeout(r, 20));
      await db.prepare("UPDATE t SET n = ? WHERE name = 'counter'").run(n + 1);
    });
    await Promise.all([bump(), bump(), bump(), bump(), bump()]);
    assert.equal(await db.prepare("SELECT n FROM t WHERE name = 'counter'").pluck().get(), 5);
  } finally {
    await fresh.drop();
  }
});

test('scoping: @uid is bound for the scoped user, and a statement naming @uid on the unscoped database fails', { skip: pgSkip }, async () => {
  const { db, fresh } = await scratch();
  try {
    const u1 = scopeDatabase(db, 'u1');
    const u2 = scopeDatabase(db, 'u2');
    await u1.prepare('INSERT INTO t (user_id, name) VALUES (@uid, ?)').run('mine');
    assert.deepEqual(await u1.prepare('SELECT name FROM t WHERE user_id = @uid').pluck().all(), ['mine']);
    assert.deepEqual(await u2.prepare('SELECT name FROM t WHERE user_id = @uid').pluck().all(), []);
    await assert.rejects(db.prepare('SELECT name FROM t WHERE user_id = @uid').all(), /Missing named parameter "uid"/);
  } finally {
    await fresh.drop();
  }
});
